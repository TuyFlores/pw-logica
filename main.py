while True :
    print ("__Calculadora__\n"
    "1 - Somar \n"
    "2 - Subtrait \n"
    "3 - Multiplicar \n"
    "4 - Sair \n")
    opcao = int(input("Escolha uma opção:"))
    if opcao == 4:
        print("Encerramos calculadora...")
        break
    if opcao == 1:
        print("Você escolheu somar")
        break
    elif opcao == 2:
        print("Você escolheu subtrair")
        break
    elif opcao == 3:
        print("Você escolheu Multiplicar")
        break
    
    else:
        print("Opção Invalida!")
    
